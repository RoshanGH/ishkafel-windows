/// **导出可以停下来。**
///
/// 产品负责人 2026-09-16：「导出一次好几十条，甚至 100 条，让导出可以取消，
/// 已经导出的就留着当导出成功的物料。」
///
/// 一批一百条要跑很久。跑到一半发现挑错了素材、或者临时要先出另一批，
/// 没有出口就只能干等——或者关掉整个 app，那一批已经导好的片子也跟着
/// 说不清楚了。
///
/// 停下来的规矩（产品负责人定的）：
/// - **已经导完的全部留着**，它们就是能交付的物料，和正常导完的没有区别
/// - **正在导的那一条丢掉**：半成品文件删掉，不留在输出目录里——它看起来
///   和成片一模一样，留着迟早被当成能交付的东西发出去
/// - 还没轮到的那些标成「已停止」，不是「失败」：失败要人去查原因，
///   停止是人自己按的
library;

/// 一批导出的停止开关。
///
/// 按下之后不可撤销——「停一半又继续」不是这一版要做的事（产品负责人：
/// 「这次先不做，停就是停」）。要再导就重新点一次导出：已经渲好的段落切片
/// 都按内容指纹留在磁盘上，重导时直接命中，不会全部重跑。
class ExportCancelToken {
  bool _cancelled = false;

  /// 按下停止。重复按无副作用
  void cancel() => _cancelled = true;

  bool get isCancelled => _cancelled;

  /// 已经按下就抛 [ExportCancelled]。
  ///
  /// **放在每次拉子进程之前**：导出的时间几乎全花在 ffmpeg 上（切片、拼接、
  /// 合成、人声分离），把检查点放在那儿，一个地方就覆盖了全部环节，
  /// 最坏只等当前这一个进程跑完
  void throwIfCancelled() {
    if (_cancelled) throw const ExportCancelled();
  }
}

/// 人按了停止。
///
/// **不是失败**：调用方接住它要标成「已停止」，别混进失败清单里让人去查
/// 原因——原因就是他自己按的
class ExportCancelled implements Exception {
  const ExportCancelled();

  @override
  String toString() => 'ExportCancelled: 导出已停止';
}
